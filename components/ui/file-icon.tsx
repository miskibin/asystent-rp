/**
 * Resolves a file path (or bare filename) to an icon id: exact filename
 * match, then filename pattern, then extension, then a generic fallback.
 */
export function fileIconId(path: string): FileIconId {
  const base = (path.split(/[\\/]/).pop() ?? path).toLowerCase()
  if (base in FILENAME_MAP) return FILENAME_MAP[base]
  for (const [pattern, id] of FILENAME_PATTERNS) {
    if (pattern.test(base)) return id
  }
  const dot = base.lastIndexOf(".")
  if (dot > 0 && dot < base.length - 1) {
    const ext = base.slice(dot + 1)
    if (ext in EXTENSION_MAP) return EXTENSION_MAP[ext]
  }
  return "document"
}

